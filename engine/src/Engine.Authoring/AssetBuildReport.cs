using VYaml.Annotations;

namespace Engine.Core;

[YamlObject]
internal sealed partial record ShippedAsset(string Path, long Bytes, string Reason, string? Bundle = null);

[YamlObject]
internal sealed partial record UnreferencedAsset(string Path, long Bytes);

// Usage is the share of the source sheet covered by used cells with their 1-pixel border. Pixels are sheet width × height
// (4 bytes each as an SDL texture).
[YamlObject]
internal sealed partial record AtlasUsage(string Path, int Cells, int UsedCells, double Usage, bool Repacked,
    long SheetBytes, long ShippedSheetBytes, long Pixels, long ShippedPixels);

[YamlObject]
internal sealed partial record AssetBuildReport(long ShippedBytes, Dictionary<string, long> BytesByType, long UnreferencedBytes,
    string[] Warnings, ShippedAsset[] Shipped, UnreferencedAsset[] Unreferenced, FeatureDecision[] Features, AtlasUsage[] Atlases)
{
    internal const string FileName = "assets.yaml";
    internal const long LargeWav = 1L << 20;

    // Sizes of the staged Game folder, taken before content bundles replace their member files.
    internal static Dictionary<string, long> Measure(string game) =>
        Directory.EnumerateFiles(game, "*", SearchOption.AllDirectories).ToDictionary(
            file => Path.GetRelativePath(game, file).Replace('\\', '/'), file => new FileInfo(file).Length, StringComparer.Ordinal);

    // 'reasons' holds the first reference chain of each walked path; everything else in Game/ was generated by the build.
    // Only Assets/ is checked for unreferenced files: other project folders hold scenes, samples' own tools and so on.
    internal static AssetBuildReport Create(string project, IReadOnlyDictionary<string, long> shipped, IReadOnlyDictionary<string, string> reasons,
        IEnumerable<AssetEntry> sources, ISet<string> dependencies, ISet<string> packedSources, string[] bundles, FeatureDecision[] features, AtlasUsage[] atlases)
    {
        static string Generated(string path) => path switch
        {
            _ when path.EndsWith(".shader.frames.png", StringComparison.Ordinal) => "baked from " + path[..^".frames.png".Length],
            _ when path.StartsWith(".monoon-compiled/", StringComparison.Ordinal) => "compiled project scripts",
            _ when path.StartsWith(TileWorld.Folder + "/", StringComparison.Ordinal) => "streamed tile chunks",
            _ when path.StartsWith(BakedShaderSheets.Builtins + "/", StringComparison.Ordinal) => "built-in shader sheet",
            _ => "build metadata"
        };
        var files = shipped.OrderByDescending(p => p.Value).ThenBy(p => p.Key, StringComparer.Ordinal)
            .Select(p => new ShippedAsset(p.Key, p.Value, reasons.GetValueOrDefault(p.Key) ?? Generated(p.Key),
                bundles.FirstOrDefault(folder => p.Key.StartsWith(folder + "/", StringComparison.Ordinal)))).ToArray();
        var unreferenced = sources.Where(e => e.Path.StartsWith("Assets/", StringComparison.Ordinal) && !dependencies.Contains(e.Path) && !packedSources.Contains(e.Path))
            .Select(e => new FileInfo(Path.Combine(project, e.Path))).Where(f => f.Exists)
            .Select(f => new UnreferencedAsset(Path.GetRelativePath(project, f.FullName).Replace('\\', '/'), f.Length))
            .OrderByDescending(u => u.Bytes).ThenBy(u => u.Path, StringComparer.Ordinal).ToArray();
        var warnings = files.Select(f => WavWarning(f.Path, f.Bytes)).OfType<string>().ToArray();
        var byType = files.GroupBy(f => Path.GetExtension(f.Path) is { Length: > 0 } ext && !Path.GetFileName(f.Path).StartsWith('.') ? ext.ToLowerInvariant() : "(none)")
            .OrderByDescending(g => g.Sum(f => f.Bytes)).ToDictionary(g => g.Key, g => g.Sum(f => f.Bytes));
        return new(files.Sum(f => f.Bytes), byType, unreferenced.Sum(u => u.Bytes), warnings, files, unreferenced, features, atlases);
    }

    // Short Console/CLI summary: totals, the ten largest shipped and unreferenced files, and warnings. The file lists everything.
    internal string[] Summary(string path) =>
    [
        $"Shipped {Shipped.Length} files, {Size(ShippedBytes)}: " + string.Join(", ", BytesByType.Take(6).Select(t => $"{t.Key} {Size(t.Value)}")),
        .. Shipped.Take(10).Select(f => $"  {Size(f.Bytes),10}  {f.Path}" + (f.Bundle == null ? "" : $" [{f.Bundle}]") + $" — {f.Reason}"),
        $"Unreferenced under Assets/: {Unreferenced.Length} files, {Size(UnreferencedBytes)} (not shipped)",
        .. Unreferenced.Take(10).Select(u => $"  {Size(u.Bytes),10}  {u.Path}"),
        .. Atlases.Select(a => $"Atlas {a.Path}: {a.UsedCells} of {a.Cells} cells used, {a.Usage:P0} of the sheet" + (a.Repacked
            ? $"; shipped repacked {Size(a.SheetBytes)} -> {Size(a.ShippedSheetBytes)}, {a.Pixels:N0} -> {a.ShippedPixels:N0} pixels" : "")),
        .. Features.Select(d => $"Engine feature {d.Feature.ToString().ToLowerInvariant()}: {(d.Included ? "included" : "left out")} — {d.Reason}"),
        .. Warnings.Select(w => "Warning: " + w),
        $"Asset report: {path}"
    ];

    // Shared by the build report and the editor's Import Assets (roadmap 15.10). Nothing converts WAV automatically.
    // shortcut: every WAV counts as PCM; check the format tag if compressed WAV (ADPCM) assets appear.
    internal static string? WavWarning(string path, long bytes) => bytes > LargeWav && path.EndsWith(".wav", StringComparison.OrdinalIgnoreCase)
        ? $"{path} is {Size(bytes)} of PCM WAV; import it as Ogg Vorbis to ship less." : null;

    // 'paths' are project-relative, as ProjectImport.Copy returns them.
    internal static string[] ImportWarnings(string project, IEnumerable<string> paths) =>
        paths.Select(p => WavWarning(p, new FileInfo(Path.Combine(project, p)).Length)).OfType<string>().ToArray();

    internal static string Size(long bytes) => bytes switch
    {
        >= 1L << 20 => $"{bytes / 1048576.0:0.0} MiB",
        >= 1L << 10 => $"{bytes / 1024.0:0.0} KiB",
        _ => $"{bytes} B"
    };
}
